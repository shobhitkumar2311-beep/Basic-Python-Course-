# Write a python program to find an average of two numbers entered by the user. 
a = input("Enter the first number: ")
b = input("Enter the Second number: ")
# In this statement we are given the two numbers by the user.
result = (int(a) + int(b)) / 2 
# This is calculating the average of two numbers entered by the user.
print("The average of",a,"and",b,"is",result)